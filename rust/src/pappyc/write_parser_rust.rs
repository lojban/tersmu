fn emit_unit_alt(dv: &str, derivs: &str, rule: &Rule, nts: &[Nonterminal]) -> String {
    let Rule::RuleAlt(alts) = rule else {
        unreachable!("emit_unit_alt: not RuleAlt");
    };
    let mut exprs: Vec<String> = Vec::new();
    for a in alts {
        if extract_unit_char_seq(a).is_some() {
            let s: String = extract_unit_char_seq(a).unwrap().iter().collect();
            exprs.push(format!("string_({:?})", s));
        } else if let Some(t) = forward_prim_supported(a, "()", nts) {
            let callee = format!("{}_parse_{}", dv, locase(t));
            exprs.push(format!("Parser::new(|dvs: {derivs}| {callee}(&dvs))"));
        } else if simple_unit_rule_seq_supported("()", a, nts) {
            let body = emit_unit_rule_seq_body(dv, derivs, a, "dvs");
            exprs.push(format!(
                "Parser::new(|dvs: {derivs}| {{\n{body}}})"
            ));
        } else {
            unreachable!("emit_unit_alt: branch not emittable");
        }
    }
    let expr = fold_choice_parsers(&exprs);
    format!("    {expr}.parse(d.clone())\n")
}

fn simple_string_alt_supported(typ: &str, rule: &Rule, nts: &[Nonterminal]) -> bool {
    if typ.trim() != "String" {
        return false;
    }
    let Rule::RuleAlt(alts) = rule else {
        return false;
    };
    !alts.is_empty()
        && alts.iter().all(|a| {
            extract_unit_char_seq(a).is_some()
                || forward_prim_supported(a, "String", nts).is_some()
                || simple_string_rule_seq_supported("String", a, nts)
        })
}

fn emit_string_alt(dv: &str, derivs: &str, rule: &Rule, nts: &[Nonterminal]) -> String {
    let Rule::RuleAlt(alts) = rule else {
        unreachable!("emit_string_alt: not RuleAlt");
    };
    let mut exprs: Vec<String> = Vec::new();
    for a in alts {
        if extract_unit_char_seq(a).is_some() {
            let s: String = extract_unit_char_seq(a).unwrap().iter().collect();
            exprs.push(format!("string_value({:?})", s));
        } else if let Some(t) = forward_prim_supported(a, "String", nts) {
            let callee = format!("{}_parse_{}", dv, locase(t));
            exprs.push(format!("Parser::new(|dvs: {derivs}| {callee}(&dvs))"));
        } else if simple_string_rule_seq_supported("String", a, nts) {
            let body = emit_string_rule_seq_body(dv, derivs, a, "dvs");
            exprs.push(format!(
                "Parser::new(|dvs: {derivs}| {{\n{body}}})"
            ));
        } else {
            unreachable!("emit_string_alt: branch not emittable");
        }
    }
    let expr = fold_choice_parsers(&exprs);
    format!("    {expr}.parse(d.clone())\n")
}

/// Nested `choice(p, choice(…))` for homogeneous `Parser<D, V>` expression strings.
fn fold_choice_parsers(exprs: &[String]) -> String {
    debug_assert!(!exprs.is_empty());
    if exprs.len() == 1 {
        return exprs[0].clone();
    }
    format!(
        "choice({}, {})",
        exprs[0],
        fold_choice_parsers(&exprs[1..])
    )
}

