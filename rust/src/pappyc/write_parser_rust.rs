/// Split `RuleSeq` matches into merged literal strings and primitive NT references.
fn unit_rule_seq_segments(ms: &[Match]) -> Option<Vec<UnitSeqSeg>> {
    let mut segs: Vec<UnitSeqSeg> = Vec::new();
    let mut lit_buf: Vec<char> = Vec::new();
    let flush = |buf: &mut Vec<char>, segs: &mut Vec<UnitSeqSeg>| {
        if !buf.is_empty() {
            segs.push(UnitSeqSeg::Lit(buf.iter().collect()));
            buf.clear();
        }
    };
    for m in ms {
        match m {
            Match::MatchAnon(Rule::RulePrim(n)) | Match::MatchName(Rule::RulePrim(n), _) => {
                flush(&mut lit_buf, &mut segs);
                segs.push(UnitSeqSeg::Prim(n.clone()));
            }
            Match::MatchNot(r) => {
                flush(&mut lit_buf, &mut segs);
                if let Some(chars) = extract_unit_char_seq(r) {
                    if chars.is_empty() {
                        return None;
                    }
                    segs.push(UnitSeqSeg::NotLit(chars.iter().collect()));
                } else if let Rule::RulePrim(n) = r {
                    segs.push(UnitSeqSeg::NotPrim(n.clone()));
                } else {
                    return None;
                }
            }
            Match::MatchAnd(r) => {
                flush(&mut lit_buf, &mut segs);
                if let Some(chars) = extract_unit_char_seq(r) {
                    if chars.is_empty() {
                        return None;
                    }
                    segs.push(UnitSeqSeg::AndLit(chars.iter().collect()));
                } else if let Rule::RulePrim(n) = r {
                    segs.push(UnitSeqSeg::AndPrim(n.clone()));
                } else {
                    return None;
                }
            }
            m => {
                let chars = match_to_literal_chars(m)?;
                lit_buf.extend(chars);
            }
        }
    }
    flush(&mut lit_buf, &mut segs);
    Some(segs)
}

fn match_to_literal_chars(m: &Match) -> Option<Vec<char>> {
    match m {
        Match::MatchAnon(r) => extract_unit_char_seq(r),
        Match::MatchName(r, _) => extract_unit_char_seq(r),
        _ => None,
    }
}

