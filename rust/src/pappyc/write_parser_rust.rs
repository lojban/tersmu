/// Reduce expands `*` / `+` to `StarRuleN` / `PlusRuleN` list nonterminals (`reduce_grammar.rs`).
fn match_reduced_star_list_rule<'a>(nt_name: &str, rule: &'a Rule) -> Option<&'a Rule> {
    let Rule::RuleAlt(alts) = rule else {
        return None;
    };
    if alts.len() != 2 {
        return None;
    }
    let Rule::RuleSeq(ms0, p0) = &alts[0] else {
        return None;
    };
    let Rule::RuleSeq(ms1, p1) = &alts[1] else {
        return None;
    };
    if !matches!(p0, Producer::ProdCode(c) if c.trim() == "v : vs") {
        return None;
    }
    if !matches!(p1, Producer::ProdCode(c) if c.trim() == "[]") {
        return None;
    }
    if !ms1.is_empty() || ms0.len() != 2 {
        return None;
    }
    let Match::MatchName(r1, v) = &ms0[0] else {
        return None;
    };
    let Match::MatchName(Rule::RulePrim(rec), vs) = &ms0[1] else {
        return None;
    };
    if v != "v" || vs != "vs" || rec != nt_name {
        return None;
    }
    Some(r1)
}

fn match_reduced_plus_list_rule<'a>(nt_name: &str, rule: &'a Rule) -> Option<&'a Rule> {
    let Rule::RuleAlt(alts) = rule else {
        return None;
    };
    if alts.len() != 2 {
        return None;
    }
    let Rule::RuleSeq(ms0, p0) = &alts[0] else {
        return None;
    };
    let Rule::RuleSeq(ms1, p1) = &alts[1] else {
        return None;
    };
    if !matches!(p0, Producer::ProdCode(c) if c.trim() == "v : vs") {
        return None;
    }
    if !matches!(p1, Producer::ProdCode(c) if c.trim() == "[v]") {
        return None;
    }
    if ms0.len() != 2 || ms1.len() != 1 {
        return None;
    }
    let Match::MatchName(r1, v) = &ms0[0] else {
        return None;
    };
    let Match::MatchName(Rule::RulePrim(rec), vs) = &ms0[1] else {
        return None;
    };
    let Match::MatchName(_, v2) = &ms1[0] else {
        return None;
    };
    if v != "v" || vs != "vs" || v2 != "v" || rec != nt_name {
        return None;
    }
    Some(r1)
}

